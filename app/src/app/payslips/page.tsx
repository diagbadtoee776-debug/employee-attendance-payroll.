"use client";

import { useEffect, useMemo, useState, type CSSProperties } from "react";
import { supabase } from "@/lib/supabase";
import { useAuth } from "@/components/AuthProvider";
import AppShell from "@/components/AppShell";

type Emp = { employee_no: string; first_name: string; last_name: string };
type Per = { label: string };
type LineType = "earning" | "allowance" | "deduction";

type RawSlip = {
  id: number;
  period_id: number;
  regular_hours: number;
  overtime_hours: number;
  gross_pay: number;
  total_allowances: number;
  total_deductions: number;
  net_pay: number;
  employees: Emp | Emp[] | null;
  pay_periods: Per | Per[] | null;
};

type Slip = {
  id: number;
  period_id: number;
  period: string;
  emp_no: string;
  emp_name: string;
  regular: number;
  overtime: number;
  gross: number;
  allowances: number;
  deductions: number;
  net: number;
};

type Line = { id: number; line_type: LineType; description: string; amount: number };

const money = new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" });
const hrs = (n: number) => n.toFixed(2);
const filterLabel: CSSProperties = { display: "grid", gap: 4, fontSize: 12, color: "var(--muted)" };

function first<T>(v: T | T[] | null | undefined): T | null {
  return Array.isArray(v) ? (v[0] ?? null) : (v ?? null);
}

export default function PayslipsPage() {
  const { user, role } = useAuth();
  const userId = user?.id ?? null;
  const isEmployee = role === "employee";

  const [slips, setSlips] = useState<Slip[]>([]);
  const [loaded, setLoaded] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [periodFilter, setPeriodFilter] = useState("all");
  const [query, setQuery] = useState("");
  const [open, setOpen] = useState<Slip | null>(null);

  useEffect(() => {
    if (!userId) return;
    let cancelled = false;
    (async () => {
      const { data, error: err } = await supabase
        .from("payslips")
        .select(
          "id, period_id, regular_hours, overtime_hours, gross_pay, total_allowances, total_deductions, net_pay, employees(employee_no, first_name, last_name), pay_periods(label)"
        )
        .order("period_id", { ascending: false })
        .order("id");
      if (cancelled) return;
      if (err) {
        setError(err.message);
        setLoaded(true);
        return;
      }
      setSlips(
        (data as unknown as RawSlip[]).map((r): Slip => {
          const e = first(r.employees);
          return {
            id: r.id,
            period_id: r.period_id,
            period: first(r.pay_periods)?.label ?? "-",
            emp_no: e?.employee_no ?? "-",
            emp_name: e ? `${e.first_name} ${e.last_name}` : "-",
            regular: Number(r.regular_hours),
            overtime: Number(r.overtime_hours),
            gross: Number(r.gross_pay),
            allowances: Number(r.total_allowances),
            deductions: Number(r.total_deductions),
            net: Number(r.net_pay),
          };
        })
      );
      setError(null);
      setLoaded(true);
    })();
    return () => {
      cancelled = true;
    };
  }, [userId]);

  const periods = useMemo(() => {
    const m = new Map<number, string>();
    slips.forEach((s) => m.set(s.period_id, s.period));
    return Array.from(m.entries())
      .map(([id, label]) => ({ id, label }))
      .sort((a, b) => b.id - a.id);
  }, [slips]);

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return slips.filter((s) => {
      if (periodFilter !== "all" && String(s.period_id) !== periodFilter) return false;
      if (!q) return true;
      return s.emp_name.toLowerCase().includes(q) || s.emp_no.toLowerCase().includes(q);
    });
  }, [slips, periodFilter, query]);

  const totals = useMemo(
    () =>
      filtered.reduce(
        (t, s) => ({
          gross: t.gross + s.gross,
          deductions: t.deductions + s.deductions,
          net: t.net + s.net,
        }),
        { gross: 0, deductions: 0, net: 0 }
      ),
    [filtered]
  );

  return (
    <AppShell
      title={isEmployee ? "My payslips" : "Payslips"}
      subtitle={isEmployee ? "Your payslips, itemized for each pay period." : "Payslips generated by payroll runs."}
    >
      {error && (
        <p className="alert" role="alert">
          {error}
        </p>
      )}

      <section className="section">
        <div className="stat-grid">
          <div className="card">
            <p className="stat-label">Payslips</p>
            <p className="stat-value">{loaded ? filtered.length : <span className="skeleton" />}</p>
          </div>
          <div className="card">
            <p className="stat-label">Total gross</p>
            <p className="stat-value">{loaded ? money.format(totals.gross) : <span className="skeleton" />}</p>
          </div>
          <div className="card">
            <p className="stat-label">Total deductions</p>
            <p className="stat-value">{loaded ? money.format(totals.deductions) : <span className="skeleton" />}</p>
          </div>
          <div className="card">
            <p className="stat-label">Total net pay</p>
            <p className="stat-value">{loaded ? money.format(totals.net) : <span className="skeleton" />}</p>
          </div>
        </div>
      </section>

      <div className="toolbar">
        <label style={filterLabel}>
          Pay period
          <select className="select" value={periodFilter} onChange={(e) => setPeriodFilter(e.target.value)}>
            <option value="all">All periods</option>
            {periods.map((p) => (
              <option key={p.id} value={p.id}>
                {p.label}
              </option>
            ))}
          </select>
        </label>
        {!isEmployee && (
          <label style={{ ...filterLabel, flex: 1, minWidth: 220 }}>
            Search
            <input
              className="input"
              type="search"
              placeholder="Name or employee number"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
            />
          </label>
        )}
      </div>

      <div className="card table-wrap">
        {!loaded ? (
          <p className="empty">Loading payslips...</p>
        ) : filtered.length === 0 ? (
          <p className="empty">No payslips to show yet.</p>
        ) : (
          <table className="table">
            <thead>
              <tr>
                {!isEmployee && <th>Employee</th>}
                <th>Period</th>
                <th>Regular h</th>
                <th>Overtime h</th>
                <th>Gross</th>
                <th>Allowances</th>
                <th>Deductions</th>
                <th>Net pay</th>
                <th aria-label="Actions" />
              </tr>
            </thead>
            <tbody>
              {filtered.map((s) => (
                <tr key={s.id}>
                  {!isEmployee && (
                    <td>
                      <p className="cell-main">{s.emp_name}</p>
                      <p className="cell-sub">{s.emp_no}</p>
                    </td>
                  )}
                  <td>{s.period}</td>
                  <td>{hrs(s.regular)}</td>
                  <td>{hrs(s.overtime)}</td>
                  <td>{money.format(s.gross)}</td>
                  <td>{money.format(s.allowances)}</td>
                  <td>{money.format(s.deductions)}</td>
                  <td className="cell-main">{money.format(s.net)}</td>
                  <td>
                    <div className="actions">
                      <button className="btn small outline" onClick={() => setOpen(s)}>
                        View
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>

      {open && <SlipDetail slip={open} onClose={() => setOpen(null)} />}
    </AppShell>
  );
}

function SlipDetail({ slip, onClose }: { slip: Slip; onClose: () => void }) {
  const [lines, setLines] = useState<Line[] | null>(null);
  const [err, setErr] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const { data, error } = await supabase
        .from("payslip_lines")
        .select("id, line_type, description, amount")
        .eq("payslip_id", slip.id)
        .order("id");
      if (cancelled) return;
      if (error) {
        setErr(error.message);
        return;
      }
      setLines(((data ?? []) as unknown as Line[]).map((l) => ({ ...l, amount: Number(l.amount) })));
    })();
    return () => {
      cancelled = true;
    };
  }, [slip.id]);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  const groups: { type: LineType; title: string }[] = [
    { type: "earning", title: "Earnings" },
    { type: "allowance", title: "Allowances" },
    { type: "deduction", title: "Deductions" },
  ];

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div
        className="modal"
        role="dialog"
        aria-modal="true"
        aria-labelledby="slip-title"
        onClick={(e) => e.stopPropagation()}
      >
        <h2 id="slip-title">Payslip: {slip.period}</h2>
        <p className="cell-sub" style={{ marginBottom: 16 }}>
          {slip.emp_name} · {slip.emp_no} · {hrs(slip.regular)} regular hours, {hrs(slip.overtime)} overtime hours
        </p>

        {err && (
          <p className="alert" role="alert">
            {err}
          </p>
        )}
        {!lines && !err && <p className="empty">Loading...</p>}

        {lines &&
          groups.map((g) => {
            const items = lines.filter((l) => l.line_type === g.type);
            if (items.length === 0) return null;
            const sub = items.reduce((t, l) => t + l.amount, 0);
            return (
              <div key={g.type} style={{ marginBottom: 16 }}>
                <p className="section-title">{g.title}</p>
                {items.map((l) => (
                  <div
                    key={l.id}
                    style={{ display: "flex", justifyContent: "space-between", padding: "6px 0" }}
                  >
                    <span>{l.description}</span>
                    <span>
                      {g.type === "deduction" ? "-" : ""}
                      {money.format(l.amount)}
                    </span>
                  </div>
                ))}
                <div
                  style={{
                    display: "flex",
                    justifyContent: "space-between",
                    padding: "8px 0 0",
                    borderTop: "1px solid var(--border)",
                    fontWeight: 600,
                  }}
                >
                  <span>Total {g.title.toLowerCase()}</span>
                  <span>{money.format(sub)}</span>
                </div>
              </div>
            );
          })}

        <div
          style={{
            display: "flex",
            justifyContent: "space-between",
            padding: "14px 16px",
            borderRadius: 12,
            background: "var(--primary-soft)",
            fontSize: 18,
            fontWeight: 700,
          }}
        >
          <span>Net pay</span>
          <span>{money.format(slip.net)}</span>
        </div>

        <div className="modal-actions" style={{ marginTop: 16 }}>
          <button className="btn ghost" onClick={onClose}>
            Close
          </button>
        </div>
      </div>
    </div>
  );
}